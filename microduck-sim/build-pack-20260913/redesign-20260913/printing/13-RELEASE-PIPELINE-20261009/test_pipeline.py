import copy,json,tempfile,unittest,zipfile
from pathlib import Path
import release_pipeline as r
class PipelineTests(unittest.TestCase):
 def setUp(self):self.m=r.read(r.HERE/'fixture-manifest.json');self.tmp=tempfile.TemporaryDirectory();self.d=Path(self.tmp.name)
 def tearDown(self):self.tmp.cleanup()
 def run_manifest(self,m):
  p=self.d/'manifest.json';r.write(p,m);return r.prepare(p,self.d/'prepared')
 def test_existing_spacer_and_exact_shared_vertices(self):
  p=self.run_manifest(self.m);self.assertEqual(len(p['rows']),2)
  for row in p['rows']:
   with zipfile.ZipFile(row['project']['path'])as z:
    root=r.ET.fromstring(z.read('3D/3dmodel.model'));vs=root.findall('.//'+r.Q+'vertex');fs=root.findall('.//'+r.Q+'triangle');self.assertLess(len(vs),len(fs)*3)
  self.assertEqual(p['baselinePrintedStockInstances'],89);self.assertGreater(p['parts'][0]['flatContactAreaMm2'],20)
 def test_source_mutation_rejected(self):
  self.m['parts'][0]['sha256']='0'*64
  with self.assertRaises(AssertionError):self.run_manifest(self.m)
 def test_scaling_rejected(self):
  self.m['parts'][0]['sourceToPrint'][0][0]=.95
  with self.assertRaises(AssertionError):self.run_manifest(self.m)
 def test_tilted_floor_rejected(self):
  import numpy as np
  theta=.1;c,s=np.cos(theta),np.sin(theta);self.m['parts'][0]['sourceToPrint']=[[1,0,0,0],[0,c,-s,0],[0,s,c,0],[0,0,0,1]]
  with self.assertRaises(AssertionError):self.run_manifest(self.m)
 def test_wrong_machine_profile_rejected(self):
  self.m['profiles']['Black_Elegoo']=self.m['profiles']['Black_Bambu']
  with self.assertRaises(AssertionError):self.run_manifest(self.m)
 def test_unprinted_stock_id_rejected(self):
  self.m['parts'][0].update(decision='replacement',replacesStockIds=['9999'])
  with self.assertRaises(AssertionError):self.run_manifest(self.m)
 def test_unchanged_stock_rejected(self):
  stock=next(x for x in r.read(r.PRINT/'copy-manifest.json')['copy_records']if 'manifest_instance_index'in x);self.m['parts'][0].update(r.ref(stock['source']))
  with self.assertRaises(AssertionError):self.run_manifest(self.m)
 def test_time_comes_from_actual_machine_header(self):
  self.assertEqual(r.time_seconds(b'; total estimated time: 1h 2m 1s\n','Bambu'),3721)
  self.assertEqual(r.time_seconds(b'; estimated printing time (normal mode) = 4m 7s\n','Elegoo'),247)
 def test_bed_violation_rejected(self):
  self.m['placements']={'Black':[dict(key='pi_spacer_fixture',copy=1,translation=[1,1,0])]}
  with self.assertRaises(AssertionError):self.run_manifest(self.m)
 def test_not_guarded_slice_rejected(self):
  import os
  old=os.environ.pop('MICRODUCK_BOUNDED_CAD',None)
  try:
   with self.assertRaises(AssertionError):r.slice_one('absent','Black','Bambu')
  finally:
   if old is not None:os.environ['MICRODUCK_BOUNDED_CAD']=old
 def arc_project(self):
  p=self.d/'arc.3mf'
  with zipfile.ZipFile(p,'w')as z:
   z.writestr('Metadata/project_settings.config',json.dumps({'initial_layer_print_height':.2}))
   z.writestr('Metadata/model_settings.config','<config><object id="1"><metadata key="name" value="sample"/></object><plate><model_instance><metadata key="object_id" value="1"/><metadata key="identify_id" value="100"/></model_instance></plate></config>')
  return p
 def test_all_layer_arc_extrema_are_in_footprint(self):
  g=b'; OBJECT_ID:100\n;TYPE:External perimeter\nM83\nG1 X110 Y100 Z0.2\nG1 X111 Y100 E1\nG1 X110 Y100 Z1\nG3 X90 Y100 I-10 J0 E2\n'
  rows,fp=r.first_layer(g,self.arc_project(),'Elegoo')
  self.assertEqual(len(rows),1);self.assertGreater(fp['allLayerModelSupportBrimBounds']['sample'][3],110)
 def orca_gcode_and_png(self):
  import io;from PIL import Image,ImageDraw
  g=(b'; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.4.2 on 2026-10-09 at 15:42:56\n; total layer number: 2\n; HEADER_BLOCK_END\n\n'
     b'; EXECUTABLE_BLOCK_START\nM104 S220\nG28\nG1 X10 Y10 Z0.2 E1\n; EXECUTABLE_BLOCK_END\n; CONFIG_BLOCK_START\n; thumbnails = 144x144/PNG\n; CONFIG_BLOCK_END\n')
  im=Image.new('RGB',(512,512),'white');ImageDraw.Draw(im).ellipse((100,100,400,400),fill=(232,120,30));b=io.BytesIO();im.save(b,'PNG');return g,b.getvalue()
 def test_centauri_preview_follows_header(self):
  g,png=self.orca_gcode_and_png();payload=r.cc_preview(g,png);c=r.check_cc_preview(payload,g)
  self.assertEqual((c['width'],c['height']),(144,144));self.assertLessEqual(c['slicerLine'],r.CC_SLICER_LINES);self.assertLess(c['previewLine'],payload.split(b'\n').index(b'M104 S220'))
 def test_preview_above_header_is_rejected(self):
  # The V1.4-V1.6 layout: a long preview prepended above '; generated by OrcaSlicer' hides the slicer from the CC firmware.
  import base64
  g,png=self.orca_gcode_and_png();enc=base64.b64encode(png).decode()
  old=(f'; thumbnail begin 512x512 {len(enc)}\n'+'\n'.join('; '+enc[i:i+78]for i in range(0,len(enc),78))+'\n; thumbnail end\n\n').encode()+g
  with self.assertRaisesRegex(AssertionError,'first 30 lines'):r.check_cc_preview(old,g)
 def test_preview_cannot_change_commands(self):
  g,png=self.orca_gcode_and_png();payload=r.cc_preview(g,png).replace(b'M104 S220',b'M104 S250')
  with self.assertRaisesRegex(AssertionError,'Command stream changed'):r.check_cc_preview(payload,g)
 def test_arc_bulge_outside_bed_is_rejected(self):
  g=b'; OBJECT_ID:100\n;TYPE:External perimeter\nM83\nG1 X140 Y250 Z0.2\nG1 X141 Y250 E1\nG1 X140 Y250 Z1\nG3 X120 Y250 I-10 J0 E2\n'
  with self.assertRaisesRegex(AssertionError,'outside printable bed'):r.first_layer(g,self.arc_project(),'Elegoo')
if __name__=='__main__':unittest.main()
